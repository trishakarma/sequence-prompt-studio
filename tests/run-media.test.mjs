import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import ts from 'typescript';
import { renderToStaticMarkup } from 'react-dom/server';
import { createElement } from 'react';
const require=createRequire(import.meta.url);
const source=ts.transpileModule(await fs.readFile(new URL('../app/run-media.tsx',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
new Function('require','module','exports',source)(require,module,module.exports);
const {RunMedia}=module.exports;
const run={id:'run-1',outputs:[{name:'Caption',text:'A very serious cat.'}],error:null};
test('saved input image appears alongside the caption',()=>{
 const html=renderToStaticMarkup(createElement(RunMedia,{run:{...run,input_image:'data:image/png;base64,aGVsbG8='}}));
 assert.match(html,/run-media with-source/);
 assert.match(html,/Input image used for this run/);
 assert.match(html,/data:image\/png;base64,aGVsbG8=/);
 assert.match(html,/A very serious cat/);
});
test('legacy and text-only runs show outputs without a broken image',()=>{
 for(const input_image of [undefined,null]){
  const html=renderToStaticMarkup(createElement(RunMedia,{run:{...run,input_image}}));
  assert.doesNotMatch(html,/<img/);
  assert.match(html,/A very serious cat/);
 }
});
test('generated image and failure details are retained',()=>{
 const html=renderToStaticMarkup(createElement(RunMedia,{run:{...run,outputs:[{name:'Art',text:'Result',image:'data:image/png;base64,aGVsbG8='}],error:'Later step failed'}}));
 assert.match(html,/Generated by Art/);
 assert.match(html,/Download image/);
 assert.match(html,/Later step failed/);
});
