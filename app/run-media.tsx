import type { Run } from '@/lib/types';

export function RunMedia({ run }: { run: Run }) {
  return (
    <div className={run.input_image ? 'run-media with-source' : 'run-media'}>
      {run.input_image && (
        <figure className="run-source">
          <figcaption>Input image</figcaption>
          <img src={run.input_image} alt="Input image used for this run" loading="lazy" />
        </figure>
      )}
      <div className="run-results">
        <h4>Generated output</h4>
        {run.outputs.map((output, index) => (
          <details key={index} open={index === run.outputs.length - 1}>
            <summary>{String(index + 1).padStart(2, '0')} · {output.name}</summary>
            <p className="output">{output.text}</p>
            {output.image && (
              <>
                <img className="generated" alt={`Generated by ${output.name}`} src={output.image} loading="lazy" />
                <a download={`sequence-${run.id}.png`} href={output.image}>Download image ↓</a>
              </>
            )}
          </details>
        ))}
        {!run.outputs.length && <p className="muted">No output saved for this run yet.</p>}
        {run.error && <p role="alert">{run.error}</p>}
      </div>
    </div>
  );
}
